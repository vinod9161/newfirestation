@section('scripts')
<!-- Select2 CSS/JS -->
<link href="https://cdn.jsdelivr.net/npm/select2@4.1.0-rc.0/dist/css/select2.min.css" rel="stylesheet" />
<script src="https://cdn.jsdelivr.net/npm/select2@4.1.0-rc.0/dist/js/select2.min.js"></script>

<script>
$(document).ready(function() {

    // ============================================================
    // 1. HELPER FUNCTIONS TO CREATE ROWS
    // ============================================================

    function getPersonnelRow(designationId, count, expense, da, total) {
        var template = document.getElementById('personnelRowTemplate');
        var clone = document.importNode(template.content, true);
        var row = clone.querySelector('tr');
        var select = row.querySelector('select.designation_select');
        if (designationId) select.value = designationId;
        row.querySelector('.no_of_person').value = count || 1;
        row.querySelector('.expense').value = expense || 0;
        row.querySelector('.da').value = da || 0;
        row.querySelector('.person_total').value = (total || 0).toFixed(2);
        return row;
    }

    function getVehicleRow(vehicleTypeId, running) {
        var template = document.getElementById('vehicleRowTemplate');
        var clone = document.importNode(template.content, true);
        var row = clone.querySelector('tr');
        var select = row.querySelector('select.vehicle_select');
        if (vehicleTypeId) select.value = vehicleTypeId;
        row.querySelector('.running_value').value = running || 0;
        return row;
    }

    function getEquipmentRow(equipmentTypeId, running) {
        var template = document.getElementById('equipmentRowTemplate');
        var clone = document.importNode(template.content, true);
        var row = clone.querySelector('tr');
        var select = row.querySelector('select.equipment_select');
        if (equipmentTypeId) select.value = equipmentTypeId;
        row.querySelector('.equipment_running_value').value = running || 0;
        return row;
    }

    // ============================================================
    // 2. TRIGGER FUNCTIONS (FIXED – wrap row with jQuery)
    // ============================================================

    function triggerVehicleRow(row) {
        $(row).find('.vehicle_select').trigger('change');
        $(row).find('.running_value').trigger('keyup');
    }

    function triggerEquipmentRow(row) {
        $(row).find('.equipment_select').trigger('change');
        $(row).find('.equipment_running_value').trigger('keyup');
    }

    // ============================================================
    // 3. POPULATE TABLES
    // ============================================================

    function populatePersonnel(personnelArray) {
        var tbody = $('#personnelTable');
        tbody.empty();
        if (!personnelArray || personnelArray.length === 0) {
            tbody.append(getPersonnelRow(null, 1, 0, 0, 0));
        } else {
            personnelArray.forEach(function(item) {
                tbody.append(getPersonnelRow(item.designation_id, item.count, item.expense, item.da, item.total));
            });
        }
        calculateTotals();
    }

    function populateVehicles(vehicleArray) {
        var tbody = $('#vehicleTable');
        tbody.empty();
        if (!vehicleArray || vehicleArray.length === 0) {
            var row = getVehicleRow(null, 0);
            tbody.append(row);
            triggerVehicleRow(row);
        } else {
            vehicleArray.forEach(function(item) {
                var row = getVehicleRow(item.vehicle_type_id, item.running);
                tbody.append(row);
                triggerVehicleRow(row);
            });
        }
        calculateTotals();
    }

    function populateEquipment(equipmentArray) {
        var tbody = $('#equipmentTable');
        tbody.empty();
        if (!equipmentArray || equipmentArray.length === 0) {
            var row = getEquipmentRow(null, 0);
            tbody.append(row);
            triggerEquipmentRow(row);
        } else {
            equipmentArray.forEach(function(item) {
                var row = getEquipmentRow(item.equipment_id, item.running);
                tbody.append(row);
                triggerEquipmentRow(row);
            });
        }
        calculateTotals();
    }

    // ============================================================
    // 4. INITIALISE SELECT2
    // ============================================================

    $('#reportSelect').select2({
        placeholder: 'Search for a report...',
        allowClear: true
    });

    // ============================================================
    // 5. REPORT SELECTION CHANGE
    // ============================================================

    $('#reportSelect').on('change', function() {
        var selected = $(this).find(':selected');
        var val = selected.val();

        if (val) {
            var type = 'fire';
            var id = val;
            $('#reportType').val(type);
            $('#reportId').val(id);

            $.ajax({
                url: '{{ route("pumping-bills.get-report", ["type" => "__TYPE__", "id" => "__ID__"]) }}'
                    .replace('__TYPE__', type)
                    .replace('__ID__', id),
                type: 'GET',
                success: function(data) {
                    // Organisation
                    $('#organisationName').val(data.organisation_name);
                    $('#address').val(data.address);
                    $('#mobile').val(data.mobile);
                    $('#email').val(data.email);
                    $('#serviceDescription').val(data.service_description);

                    // Tables
                    populatePersonnel(data.personnel);
                    populateVehicles(data.vehicles);
                    populateEquipment(data.equipments);
                },
                error: function() {
                    alert('Could not fetch report details.');
                }
            });
        } else {
            // Clear all
            $('#reportType').val('');
            $('#reportId').val('');
            $('#organisationName').val('');
            $('#address').val('');
            $('#mobile').val('');
            $('#email').val('');
            $('#serviceDescription').val('');
            populatePersonnel([]);
            populateVehicles([]);
            populateEquipment([]);
        }
    });

    // ============================================================
    // 6. ADD / REMOVE ROWS
    // ============================================================

    // Personnel
    $('#addPersonnelRow').click(function() {
        var row = getPersonnelRow(null, 1, 0, 0, 0);
        $('#personnelTable').append(row);
        calculateTotals();
    });
    $(document).on('click', '.removePersonnelRow', function() {
        $(this).closest('tr').remove();
        calculateTotals();
    });

    // Vehicles
    $('#addVehicleRow').click(function() {
        var row = getVehicleRow(null, 0);
        $('#vehicleTable').append(row);
        triggerVehicleRow(row);
        calculateTotals();
    });
    $(document).on('click', '.removeVehicleRow', function() {
        $(this).closest('tr').remove();
        calculateTotals();
    });

    // Equipment
    $('#addEquipmentRow').click(function() {
        var row = getEquipmentRow(null, 0);
        $('#equipmentTable').append(row);
        triggerEquipmentRow(row);
        calculateTotals();
    });
    $(document).on('click', '.removeEquipmentRow', function() {
        $(this).closest('tr').remove();
        calculateTotals();
    });

    // ============================================================
    // 7. EVENT HANDLERS FOR CALCULATIONS
    // ============================================================

    // Personnel: designation change
    $(document).on('change', '.designation_select', function() {
        var row = $(this).closest('tr');
        var expense = $(this).find(':selected').data('expense') || 0;
        var da = $(this).find(':selected').data('da') || 0;
        row.find('.expense').val(expense);
        row.find('.da').val(da);
        row.find('.no_of_person').trigger('keyup');
    });

    // Personnel: number of persons
    $(document).on('keyup change', '.no_of_person', function() {
        var row = $(this).closest('tr');
        var count = parseFloat($(this).val()) || 0;
        var expense = parseFloat(row.find('.expense').val()) || 0;
        var da = parseFloat(row.find('.da').val()) || 0;
        var total = (expense * count) * (1 + (da / 100));
        row.find('.person_total').val(total.toFixed(2));
        calculateTotals();
    });

    // Vehicle: selection
    $(document).on('change', '.vehicle_select', function() {
        var row = $(this).closest('tr');
        var mileage = $(this).find(':selected').data('mileage') || 0;
        var type = $(this).find(':selected').data('type') || '';
        row.find('.mileage_value').val(mileage);
        row.find('.mileage_type').val(type);
        row.find('.running_value').trigger('keyup');
    });

    // Vehicle: running (KM)
    $(document).on('keyup change', '.running_value', function() {
        var row = $(this).closest('tr');
        var running = parseFloat($(this).val()) || 0;
        var mileage = parseFloat(row.find('.mileage_value').val()) || 0;
        var dieselRate = parseFloat($('#dieselRate').val()) || 0;
        var mileageType = row.find('.mileage_type').val();
        var dieselUsed = 0;

        if (mileageType == 'per_km') {
            dieselUsed = mileage > 0 ? running / mileage : 0;
        } else {
            dieselUsed = running * mileage;
        }

        var total = dieselUsed * dieselRate;
        row.find('.vehicle_diesel_used').val(dieselUsed.toFixed(2));
        row.find('.vehicle_total').val(total.toFixed(2));
        calculateTotals();
    });

    // Equipment: selection
    $(document).on('change', '.equipment_select', function() {
        var row = $(this).closest('tr');
        var mileage = $(this).find(':selected').data('mileage') || 0;
        var type = $(this).find(':selected').data('type') || '';
        row.find('.equipment_mileage_value').val(mileage);
        row.find('.equipment_mileage_type').val(type);
        row.find('.equipment_running_value').trigger('keyup');
    });

    // Equipment: running (Hours)
    $(document).on('keyup change', '.equipment_running_value', function() {
        var row = $(this).closest('tr');
        var running = parseFloat($(this).val()) || 0;
        var mileage = parseFloat(row.find('.equipment_mileage_value').val()) || 0;
        var dieselRate = parseFloat($('#dieselRate').val()) || 0;
        var mileageType = row.find('.equipment_mileage_type').val();
        var dieselUsed = 0;

        if (mileageType == 'per_km') {
            dieselUsed = mileage > 0 ? running / mileage : 0;
        } else {
            dieselUsed = running * mileage;
        }

        var total = dieselUsed * dieselRate;
        row.find('.equipment_diesel_used').val(dieselUsed.toFixed(2));
        row.find('.equipment_total').val(total.toFixed(2));
        calculateTotals();
    });

    // Diesel rate change – recalculate all rows
    $('#dieselRate').on('change keyup', function() {
        $('.running_value').each(function() {
            $(this).trigger('keyup');
        });
        $('.equipment_running_value').each(function() {
            $(this).trigger('keyup');
        });
    });

    // ============================================================
    // 8. CALCULATE BILLING SUMMARY
    // ============================================================

    function calculateTotals() {
        let personnelTotal = 0;
        $('.person_total').each(function() {
            personnelTotal += parseFloat($(this).val()) || 0;
        });
        let vehicleTotal = 0;
        $('.vehicle_total').each(function() {
            vehicleTotal += parseFloat($(this).val()) || 0;
        });
        let equipmentTotal = 0;
        $('.equipment_total').each(function() {
            equipmentTotal += parseFloat($(this).val()) || 0;
        });
        let totalFuelExpense = vehicleTotal + equipmentTotal;
        let depreciation = totalFuelExpense * 0.25;
        $('#fuelExpense').val(totalFuelExpense.toFixed(2));
        $('#depreciationExpense').val(depreciation.toFixed(2));
        $('#personnelExpense').val(personnelTotal.toFixed(2));
        let subtotal = totalFuelExpense + depreciation + personnelTotal;
        let cgst = subtotal * 0.09;
        let sgst = subtotal * 0.09;
        let grand = subtotal + cgst + sgst;
        $('#cgstAmount').val(cgst.toFixed(2));
        $('#sgstAmount').val(sgst.toFixed(2));
        $('#grandTotal').val(grand.toFixed(2));
    }

    // ============================================================
    // 9. INITIALISE WITH ONE EMPTY ROW FOR EACH TABLE
    // ============================================================

    populatePersonnel([]);
    populateVehicles([]);
    populateEquipment([]);
});
</script>
